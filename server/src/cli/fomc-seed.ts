// Writes the FOMC seed (src/seed/fomc.ts): every change of the federal funds rate's target since
// 1982 (FRED: DFEDTAR to December 2008, the range's DFEDTARL/DFEDTARU since) and every FOMC
// decision since 2013 held or moved (TradingView's calendar, as the macro engine keeps it), so the
// fact-check can set "this is our third cut", "unchanged since December" or "the range is 4 to 4¼
// percent" beside the record without a network.
//
//   npm run seed:fomc        (from server/, after npm run build)

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as fred from "../providers/fred.js";
import { usReleases } from "../providers/macroengine.js";

type Point = { date: string; value: number };

const day = (d: string, n: number) => new Date(Date.parse(`${d}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10);

async function main(): Promise<void> {
  const [single, low, high] = await Promise.all([fred.series("DFEDTAR", 100_000), fred.series("DFEDTARL", 100_000), fred.series("DFEDTARU", 100_000)]);
  const lowOn = new Map(low.map((p) => [p.date, p.value]));
  // One path of (date, low, high): the single target to the range's first day, then the range.
  const path: Array<{ date: string; low: number; high: number }> = [
    ...single.filter((p) => p.date < (high[0]?.date ?? "9999")).map((p: Point) => ({ date: p.date, low: p.value, high: p.value })),
    ...high.map((p: Point) => ({ date: p.date, low: lowOn.get(p.date) ?? p.value - 0.25, high: p.value })),
  ];
  const releases = await usReleases().catch(() => []);
  const decisions = releases
    .filter((r) => r.title === "Fed Interest Rate Decision" && r.actual !== null)
    .map((r) => ({ date: r.date.slice(0, 10), high: r.actual!, previous: r.previous }))
    .sort((a, b) => a.date.localeCompare(b.date));
  const decidedOn = new Set(decisions.map((d) => d.date));

  const moves: Array<{ decided: string; effective: string; low: number; high: number; changeBp: number }> = [];
  for (let k = 1; k < path.length; k++) {
    const [was, now] = [path[k - 1], path[k]];
    if (now.high === was.high && now.low === was.low) continue;
    // The range moves the day after the decision; the single target moved the day it was decided.
    const before = day(now.date, -1);
    const decided = decidedOn.has(before) || now.date >= "2008-12-16" ? before : now.date;
    moves.push({ decided, effective: now.date, low: now.low, high: now.high, changeBp: Math.round((now.high - was.high) * 100) });
  }
  const meetings = decisions.map((d) => ({ date: d.date, high: d.high, changeBp: d.previous === null ? 0 : Math.round((d.high - d.previous) * 100) }));

  const through = path.at(-1)!.date;
  const file = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "seed", "fomc.ts");
  const body = `// Generated by src/cli/fomc-seed.ts (npm run seed:fomc) on ${new Date().toISOString().slice(0, 10)}: do not edit by hand.
// The federal funds rate's target (FRED DFEDTAR to 2008-12-15, DFEDTARL/DFEDTARU since) and the
// FOMC's decisions since 2013 (TradingView's calendar), through ${through}.

/** A change of the target: when it was decided and took effect, the new range (low = high before 2008-12-16), and the move of its top. */
export type FomcMove = { decided: string; effective: string; low: number; high: number; changeBp: number };
/** An FOMC decision, a hold or a move: its day, the top of the range it set, and the move. */
export type FomcMeeting = { date: string; high: number; changeBp: number };

export const FOMC_THROUGH = ${JSON.stringify(through)};
export const FOMC_MOVES: FomcMove[] = ${JSON.stringify(moves, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
export const FOMC_MEETINGS_SEEN: FomcMeeting[] = ${JSON.stringify(meetings, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;
  writeFileSync(file, body);
  console.log(`seed: ${moves.length} moves since ${path[0].date}, ${meetings.length} decisions since ${meetings[0]?.date ?? "-"}, through ${through} → ${file}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
